#!/bin/sh
set -eu

# Build-only dependencies stay inside this project. No sudo, Homebrew mutation,
# system gem install, Xcode license acceptance, or app source changes.
app_root="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
toolchain="$app_root/.toolchain"
downloads="$toolchain/downloads"
sources="$toolchain/build-src"
logs="$toolchain/logs"
jobs="${MACOS_BUILD_JOBS:-4}"
case "$jobs" in ''|*[!0-9]*|0) echo 'MACOS_BUILD_JOBS must be a positive integer.' >&2; exit 1 ;; esac
if [ "$(uname -s)" != Darwin ] || [ "$(uname -m)" != arm64 ]; then
  echo 'This pinned bootstrap currently targets macOS arm64.' >&2; exit 1
fi
mkdir -p "$downloads" "$sources" "$logs" "$toolchain/deps" "$toolchain/bin"
if ! mkdir "$toolchain/setup-macos-build.lock" 2>/dev/null; then
  echo 'Another local toolchain setup is running (setup-macos-build.lock exists).' >&2; exit 1
fi
trap 'rmdir "$toolchain/setup-macos-build.lock"' EXIT
trap 'exit 130' INT
trap 'exit 143' HUP TERM

fetch() {
  archive="$downloads/$1"
  expected="$2"
  url="$3"
  if [ ! -f "$archive" ]; then
    curl -fL --retry 3 --connect-timeout 20 --max-time 600 "$url" -o "$archive.part"
    mv "$archive.part" "$archive"
  fi
  actual="$(shasum -a 256 "$archive" | cut -d ' ' -f 1)"
  if [ "$actual" != "$expected" ]; then echo "Checksum mismatch: $archive" >&2; exit 1; fi
}
run_logged() {
  label="$1"; shift
  echo "Building $label (log: .toolchain/logs/$label.log)"
  if ! "$@" > "$logs/$label.log" 2>&1; then tail -n 40 "$logs/$label.log" >&2; exit 1; fi
}

fetch ruby-3.4.11.tar.gz 5c22be44524312b3d433d68739bcc530633b1da5ef8ba0afa0a37680da17d3de \
  https://cache.ruby-lang.org/pub/ruby/3.4/ruby-3.4.11.tar.gz
fetch openssl-3.5.9.tar.gz 603f5602e2eef00d77fbd429d34dcd5822bb301757a1bc9cdb24c670f1eb859a \
  https://github.com/openssl/openssl/releases/download/openssl-3.5.9/openssl-3.5.9.tar.gz
fetch yaml-0.2.5.tar.gz c642ae9b75fee120b2d96c712538bd2cf283228d2337df2cf2988e3c02678ef4 \
  https://pyyaml.org/download/libyaml/yaml-0.2.5.tar.gz

# CLT is sufficient for Ruby and avoids invoking the Xcode first-launch flow.
# This variable is scoped to build commands and never persisted for Flutter.
if [ ! -f "$toolchain/deps/libyaml/lib/libyaml.a" ]; then
  tar -xzf "$downloads/yaml-0.2.5.tar.gz" -C "$sources"
  (
    cd "$sources/yaml-0.2.5"
    run_logged libyaml-configure env DEVELOPER_DIR=/Library/Developer/CommandLineTools \
      ./configure --prefix="$toolchain/deps/libyaml" --disable-shared
    run_logged libyaml-build env DEVELOPER_DIR=/Library/Developer/CommandLineTools make -j"$jobs"
    run_logged libyaml-install env DEVELOPER_DIR=/Library/Developer/CommandLineTools make install
  )
fi
if [ ! -x "$toolchain/deps/openssl/bin/openssl" ]; then
  tar -xzf "$downloads/openssl-3.5.9.tar.gz" -C "$sources"
  (
    cd "$sources/openssl-3.5.9"
    run_logged openssl-configure env DEVELOPER_DIR=/Library/Developer/CommandLineTools \
      perl ./Configure darwin64-arm64-cc no-shared no-tests --prefix="$toolchain/deps/openssl" \
      --openssldir="$toolchain/deps/openssl/ssl"
    run_logged openssl-build env DEVELOPER_DIR=/Library/Developer/CommandLineTools make -j"$jobs" build_sw
    run_logged openssl-install env DEVELOPER_DIR=/Library/Developer/CommandLineTools make install_sw
  )
fi
mkdir -p "$toolchain/deps/openssl/ssl"
cp /etc/ssl/cert.pem "$toolchain/deps/openssl/ssl/cert.pem"

if ! "$toolchain/ruby/bin/ruby" -ropenssl -rpsych -e 'abort unless RUBY_VERSION == "3.4.11"' >/dev/null 2>&1; then
  if [ ! -f "$sources/ruby-3.4.11/configure" ]; then
    tar -xzf "$downloads/ruby-3.4.11.tar.gz" -C "$sources"
  fi
  (
    cd "$sources/ruby-3.4.11"
    run_logged ruby-configure env DEVELOPER_DIR=/Library/Developer/CommandLineTools \
      ./configure -C --prefix="$toolchain/ruby" --disable-install-doc --disable-yjit --disable-rjit \
      --disable-dtrace --with-openssl-dir="$toolchain/deps/openssl" --with-libyaml-dir="$toolchain/deps/libyaml"
    run_logged ruby-build env DEVELOPER_DIR=/Library/Developer/CommandLineTools make -j"$jobs"
    run_logged ruby-install env DEVELOPER_DIR=/Library/Developer/CommandLineTools make install
  )
fi

# The generated environment is intentionally project-local and does not set
# DEVELOPER_DIR; the standard Flutter build must use the user's selected Xcode.
python3 - "$toolchain" <<'PY'
from pathlib import Path
import shlex, sys
root = Path(sys.argv[1]).resolve()
values = dict(BUNDLE_GEMFILE=str(root.parent / 'Gemfile'), BUNDLE_PATH=str(root / 'gems'),
    BUNDLE_APP_CONFIG=str(root / 'bundle-config'), BUNDLE_USER_HOME=str(root / 'bundle-user'),
    GEM_HOME=str(root / 'gems/ruby/3.4.0'),
    GEM_PATH=f'{root}/gems/ruby/3.4.0:{root}/ruby/lib/ruby/gems/3.4.0',
    CP_HOME_DIR=str(root / 'cocoapods'), CP_CACHE_DIR=str(root / 'cocoapods/cache'),
    COCOAPODS_DISABLE_STATS='true')
lines = ['# Generated by tool/setup-macos-build.sh; source from this project only.']
lines += [f'export {key}={shlex.quote(value)}' for key, value in values.items()]
lines += [f'export PATH={shlex.quote(str(root / "bin") + ":" + str(root / "ruby/bin"))}:"$PATH"']
(root / 'macos-build-env.sh').write_text('\n'.join(lines) + '\n')
PY
. "$toolchain/macos-build-env.sh"
if [ -f "$app_root/Gemfile.lock" ]; then
  run_logged bundle-install env DEVELOPER_DIR=/Library/Developer/CommandLineTools BUNDLE_FROZEN=true \
    "$toolchain/ruby/bin/ruby" "$toolchain/ruby/bin/bundle" install --jobs "$jobs" --retry 3
else
  run_logged bundle-install env DEVELOPER_DIR=/Library/Developer/CommandLineTools \
    "$toolchain/ruby/bin/ruby" "$toolchain/ruby/bin/bundle" install --jobs "$jobs" --retry 3
fi
cat > "$toolchain/bin/pod" <<'SH'
#!/bin/sh
set -eu
toolchain="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
. "$toolchain/macos-build-env.sh"
exec "$toolchain/ruby/bin/ruby" "$toolchain/ruby/bin/bundle" exec pod "$@"
SH
chmod +x "$toolchain/bin/pod"
pod_version="$("$toolchain/bin/pod" --version)"
echo "$pod_version"
"$toolchain/ruby/bin/ruby" -rjson -ropenssl -rpsych -e \
  'puts JSON.pretty_generate({ruby: RUBY_VERSION, platform: RUBY_PLATFORM, openssl: OpenSSL::OPENSSL_LIBRARY_VERSION, libyaml: Psych.libyaml_version.join(".")})' \
  > "$toolchain/runtime-versions.json"
python3 - "$toolchain" "$app_root/Gemfile.lock" "$pod_version" <<'PY'
import hashlib, json, pathlib, sys
root, lockfile = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
report = json.loads((root / 'runtime-versions.json').read_text())
report.update(cocoapods=sys.argv[3], bundler='2.6.9',
    gemfile_lock_sha256=hashlib.sha256(lockfile.read_bytes()).hexdigest(),
    sources={
      'ruby': {'url':'https://cache.ruby-lang.org/pub/ruby/3.4/ruby-3.4.11.tar.gz', 'sha256':'5c22be44524312b3d433d68739bcc530633b1da5ef8ba0afa0a37680da17d3de'},
      'openssl': {'url':'https://github.com/openssl/openssl/releases/download/openssl-3.5.9/openssl-3.5.9.tar.gz', 'sha256':'603f5602e2eef00d77fbd429d34dcd5822bb301757a1bc9cdb24c670f1eb859a'},
      'libyaml': {'url':'https://pyyaml.org/download/libyaml/yaml-0.2.5.tar.gz', 'sha256':'c642ae9b75fee120b2d96c712538bd2cf283228d2337df2cf2988e3c02678ef4'}},
    scope='Project-local macOS build dependencies only; excluded from app bundles')
(root / 'macos-build-toolchain.json').write_text(json.dumps(report,indent=2)+'\n')
PY
echo "Ready: source '$toolchain/macos-build-env.sh' before the standard Flutter build."
